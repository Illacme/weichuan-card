#!/usr/bin/env python3
"""把 backend/migrations/*.sql 的文件清单生成为一个 Go 常量（编进二进制）。

为什么需要这份清单
------------------
migrations 是**二进制之外的文件**。线上升级时若只替换了二进制、没同步
migrations/ 目录，程序会对着旧目录得出「数据库已是最新」——没有报错、没有告警，
直到运行时某次写库才撞 `Unknown column`（2026-11-03 事故：目录停在 0034，
缺 0035 的 subscribe_tmpl_id，全程零日志线索）。

把「本版本应该带哪些迁移文件」编进二进制后，启动时一比对就能发现包不完整，
错误信息直接告诉你缺哪几个文件、该怎么做（见 internal/migrate/apply.go 的守门）。

用法
----
    python3 scripts/gen_migrations_manifest.py

新增 / 改名 / 删除迁移文件后**必须重跑**。CI 的
`TestManifestMatchesMigrationsDir` 会比对两边，漏跑直接红。
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent
MIGRATIONS_DIR = REPO_ROOT / "backend/migrations"
OUT = REPO_ROOT / "backend/internal/migrate/manifest_gen.go"

files = sorted(p.name for p in MIGRATIONS_DIR.glob("*.sql"))
if not files:
    sys.exit(f"❌ {MIGRATIONS_DIR} 下没有 .sql 文件，拒绝生成空清单")

lines = [
    "// Code generated by scripts/gen_migrations_manifest.py; DO NOT EDIT.",
    "",
    "package migrate",
    "",
    "// expectedMigrations 是**本版本** migrations 目录应有文件的清单，编译进二进制。",
    "//",
    "// 用途：启动时与磁盘上的目录比对，发现「只换了二进制、没同步 migrations/ 目录」",
    "// 这类部署事故（详见脚本头部注释与 apply.go 的守门）。顺序即应用顺序。",
    "var expectedMigrations = []string{",
]
lines += [f'\t"{name}",' for name in files]
lines += ["}", ""]

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"✓ 已写入 {OUT.relative_to(REPO_ROOT)}（{len(files)} 个迁移文件，最后一个 {files[-1]}）")
